import {cleanup,fireEvent,render,screen,waitFor,within} from '@testing-library/react'
import {afterEach,beforeEach,describe,expect,it,vi} from 'vitest'
import Account from './Account'
import {AppSessionProvider,type AppSession} from '../../context/AppSessionContext'
const mocks=vi.hoisted(()=>({list:vi.fn(),accept:vi.fn(),code:vi.fn(),remove:vi.fn(),preferences:vi.fn(),update:vi.fn()}))
vi.mock('../../api/database',()=>({createDatabaseApiClient:()=>({pendingInvitations:mocks.list,acceptInvitation:mocks.accept,joinByCode:mocks.code,deleteAccount:mocks.remove,alerts:()=>({preferences:mocks.preferences,updatePreferences:mocks.update})}),DatabaseApiClientError:class extends Error{constructor(public status:number,public statusText?:string,public payload?:unknown){super()}}}))
vi.mock('../../auth/cognito',()=>({authConfiguration:()=>({apiUrl:'https://api.example.test'})}))
vi.mock('../Production/EmailVerification',()=>({default:()=><p>Email verification</p>}))
const organizations=[{id:'agency',slug:'agency',name:'The Agency at UF',role:'member' as const},{id:'lab',slug:'lab',name:'Media Lab',role:'admin' as const,logoUrl:'https://cdn.example.test/lab.png'}]
function renderAccount(overrides:Partial<AppSession>={},initialTab?:'security'|'notifications') {
  const session:AppSession={email:'roger@example.test',isAdmin:false,setEmail:vi.fn(),setIsAdmin:vi.fn(),mode:'authenticated',getAccessToken:async()=>'token',organizations,selectedOrganizationId:'agency',setSelectedOrganizationId:vi.fn(),refreshOrganizations:vi.fn().mockResolvedValue(undefined),signOut:vi.fn(),...overrides}
  render(<AppSessionProvider value={session}><Account initialTab={initialTab}/></AppSessionProvider>)
  return session
}
beforeEach(()=>{vi.clearAllMocks();mocks.list.mockResolvedValue({items:[]});mocks.accept.mockResolvedValue({organizationId:'studio'});mocks.code.mockResolvedValue({organizationId:'studio'});mocks.preferences.mockResolvedValue({equipmentEmail:false,version:0});mocks.update.mockResolvedValue({equipmentEmail:true,version:1})})
afterEach(cleanup)
describe('Account page',()=>{
  it('lists workspaces with logos or monograms and switches the current one',async()=>{
    const session=renderAccount()
    expect(screen.getByRole('heading',{level:1,name:'roger@example.test'})).toBeInTheDocument()
    expect(screen.getByText('Member of The Agency at UF')).toBeInTheDocument()
    const agency=screen.getByRole('radio',{name:/The Agency at UF/}),lab=screen.getByRole('radio',{name:/Media Lab/})
    expect(agency).toBeChecked()
    expect(agency.closest('label')).toHaveTextContent('A')
    expect(lab.closest('label')?.querySelector('img')).toHaveAttribute('src','https://cdn.example.test/lab.png')
    fireEvent.click(lab)
    expect(session.setSelectedOrganizationId).toHaveBeenCalledWith('lab')
    await screen.findByText(/No pending invitations/)
  })
  it('accepts an invitation and makes it the current workspace',async()=>{
    mocks.list.mockResolvedValue({items:[{id:'invite',organizationId:'studio',organizationName:'Studio',role:'member',expiresAt:'2026-12-01'}]})
    const session=renderAccount()
    fireEvent.click(await screen.findByRole('button',{name:'Join Studio'}))
    expect(await screen.findByRole('status')).toHaveTextContent('Joined Studio.')
    expect(mocks.accept).toHaveBeenCalledWith('invite','studio')
    expect(session.refreshOrganizations).toHaveBeenCalledOnce()
    expect(session.setSelectedOrganizationId).toHaveBeenCalledWith('studio')
  })
  it('requires a join code and reports an invalid one without joining',async()=>{
    const {DatabaseApiClientError}=await import('../../api/database')
    const session=renderAccount()
    await screen.findByText(/No pending invitations/)
    fireEvent.click(screen.getByRole('button',{name:'Join workspace'}))
    expect(screen.getByText('Enter the join code from your workspace administrator.')).toBeInTheDocument()
    expect(mocks.code).not.toHaveBeenCalled()
    mocks.code.mockRejectedValue(new (DatabaseApiClientError as unknown as new(status:number)=>Error)(404))
    fireEvent.change(screen.getByRole('textbox',{name:'Have a join code?'}),{target:{value:'WRONG-CODE'}})
    fireEvent.click(screen.getByRole('button',{name:'Join workspace'}))
    expect(await screen.findByText(/That join code is not valid/)).toBeInTheDocument()
    expect(session.refreshOrganizations).not.toHaveBeenCalled()
  })
  it('tells a removed member that a join code cannot bring them back',async()=>{
    const {DatabaseApiClientError}=await import('../../api/database')
    const session=renderAccount()
    await screen.findByText(/No pending invitations/)
    mocks.code.mockRejectedValue(new (DatabaseApiClientError as unknown as new(status:number)=>Error)(409))
    fireEvent.change(screen.getByRole('textbox',{name:'Have a join code?'}),{target:{value:'K5K67-A0EHQ'}})
    fireEvent.click(screen.getByRole('button',{name:'Join workspace'}))
    expect(await screen.findByText(/You were removed from this workspace/)).toBeInTheDocument()
    expect(screen.queryByText(/could not be checked/)).not.toBeInTheDocument()
    expect(session.refreshOrganizations).not.toHaveBeenCalled()
  })
  it('switches sections and signs out from the section menu',()=>{
    const session=renderAccount()
    const sections=screen.getByRole('navigation',{name:'Account sections'})
    fireEvent.click(within(sections).getByRole('button',{name:'Profile'}))
    expect(screen.getByRole('textbox',{name:'Email'})).toHaveValue('roger@example.test')
    expect(screen.getByText('Email verification')).toBeInTheDocument()
    fireEvent.click(within(sections).getByRole('button',{name:'Sign out'}))
    expect(session.signOut).toHaveBeenCalledOnce()
  })
  it('does not load invitations in preview',()=>{
    renderAccount({mode:'preview',getAccessToken:undefined})
    expect(screen.getByText('Sign in to see invitations for your email.')).toBeInTheDocument()
    expect(mocks.list).not.toHaveBeenCalled()
  })
  it('deletes the account only after the email is retyped, then signs out',async()=>{
    mocks.remove.mockResolvedValue({deleted:true})
    const session=renderAccount({},'security')
    fireEvent.click(screen.getByRole('button',{name:'Delete account'}))
    const confirm=screen.getByRole('button',{name:'Delete account permanently'})
    expect(confirm).toBeDisabled()
    fireEvent.change(screen.getByLabelText('Type roger@example.test to confirm'),{target:{value:'someone@example.test'}})
    expect(confirm).toBeDisabled()
    fireEvent.change(screen.getByLabelText('Type roger@example.test to confirm'),{target:{value:' Roger@Example.test '}})
    fireEvent.click(confirm)
    await vi.waitFor(()=>expect(session.signOut).toHaveBeenCalledOnce())
    expect(mocks.remove).toHaveBeenCalledOnce()
  })
  it('keeps the person signed in and explains when deletion fails',async()=>{
    mocks.remove.mockRejectedValue(new Error('offline'))
    const session=renderAccount({},'security')
    fireEvent.click(screen.getByRole('button',{name:'Delete account'}))
    fireEvent.change(screen.getByLabelText('Type roger@example.test to confirm'),{target:{value:'roger@example.test'}})
    fireEvent.click(screen.getByRole('button',{name:'Delete account permanently'}))
    expect(await screen.findByRole('alert')).toHaveTextContent('could not be deleted')
    expect(session.signOut).not.toHaveBeenCalled()
    fireEvent.click(screen.getByRole('button',{name:'Cancel'}))
    expect(screen.queryByRole('button',{name:'Delete account permanently'})).not.toBeInTheDocument()
  })
  it('hides account deletion outside a real signed-in session',()=>{
    renderAccount({mode:'preview' as AppSession['mode'],getAccessToken:undefined},'security')
    expect(screen.queryByRole('button',{name:'Delete account'})).not.toBeInTheDocument()
  })
  it('shows why the server refused to delete the account',async()=>{
    const {DatabaseApiClientError}=await import('../../api/database')
    mocks.remove.mockRejectedValue(new DatabaseApiClientError(409,undefined,{error:'Make someone else an owner of Media Lab before deleting your account'}))
    renderAccount({},'security')
    fireEvent.click(screen.getByRole('button',{name:'Delete account'}))
    fireEvent.change(screen.getByLabelText('Type roger@example.test to confirm'),{target:{value:'roger@example.test'}})
    fireEvent.click(screen.getByRole('button',{name:'Delete account permanently'}))
    expect(await screen.findByRole('alert')).toHaveTextContent('owner of Media Lab')
  })
})

describe('Account notifications',()=>{
  it('defaults equipment email off and saves an explicit opt-in for the current workspace',async()=>{
    renderAccount({},'notifications')
    const check=await screen.findByRole('checkbox',{name:'Email me about equipment alerts'})
    await waitFor(()=>expect(check).toBeEnabled())
    expect(check).not.toBeChecked()
    expect(screen.getByText(/conflicts in The Agency at UF/)).toBeInTheDocument()
    fireEvent.click(check)
    await waitFor(()=>expect(mocks.update).toHaveBeenCalledWith({equipmentEmail:true,version:0}))
    expect(await screen.findByRole('status')).toHaveTextContent('Equipment email enabled.')
    expect(check).toBeChecked()
  })
  it('flips the preference at once and rolls it back when saving fails',async()=>{
    let reject!:(e:unknown)=>void
    mocks.update.mockReturnValue(new Promise((_,b)=>{reject=b}))
    renderAccount({},'notifications')
    const check=await screen.findByRole('checkbox',{name:'Email me about equipment alerts'})
    await waitFor(()=>expect(check).toBeEnabled())
    fireEvent.click(check)
    expect(check).toBeChecked()
    expect(check).toBeDisabled()
    reject(new Error('private'))
    expect(await screen.findByRole('alert')).toHaveTextContent('service is unavailable')
    expect(check).not.toBeChecked()
    expect(check).toBeEnabled()
  })
  it('asks preview visitors to sign in instead of showing the toggle',()=>{
    renderAccount({mode:'preview' as AppSession['mode'],getAccessToken:undefined},'notifications')
    expect(screen.getByText(/Sign in and choose a workspace/)).toBeInTheDocument()
    expect(screen.queryByRole('checkbox')).not.toBeInTheDocument()
  })
})
